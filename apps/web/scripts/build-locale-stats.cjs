#!/usr/bin/env node
/**
 * Übersetzungsstand pro Sprache berechnen und als TypScript-Modul ablegen.
 *
 * Zähler: Nenner = Keys, deren deutsche Übersetzung vom englischen Original
 * abweicht (übersetzbar); Zähler = davon Keys, deren Wert in der Zielsprache
 * gesetzt ist und vom Original abweicht. Läuft automatisch vor jedem Build
 * (`prebuild`), damit die Anzeige auf der Login-Seite nie veraltet.
 */
const fs = require("node:fs");
const path = require("node:path");

const MESSAGES_DIR = path.join(__dirname, "..", "src", "lib", "..", "..", "messages");
const OUT_FILE = path.join(__dirname, "..", "src", "lib", "locale-coverage.generated.ts");
const SOURCE = "en";

function flat(obj, prefix, out) {
  for (const [key, value] of Object.entries(obj)) {
    if (value !== null && typeof value === "object") flat(value, `${prefix}${key}.`, out);
    else out[`${prefix}${key}`] = value;
  }
  return out;
}

function readCatalog(code) {
  const file = path.join(MESSAGES_DIR, `${code}.json`);
  return flat(JSON.parse(fs.readFileSync(file, "utf-8")), "", {});
}

const codes = fs.readdirSync(MESSAGES_DIR)
  .filter((f) => /^[a-z]{2}\.json$/.test(f))
  .map((f) => f.slice(0, 2))
  .sort();
if (!codes.includes(SOURCE)) {
  console.error(`Quelle ${SOURCE}.json fehlt in ${MESSAGES_DIR}`);
  process.exit(1);
}

const source = readCatalog(SOURCE);
const german = codes.includes("de") ? readCatalog("de") : {};
const translatable = Object.keys(source).filter((k) => german[k] !== source[k]);
const total = translatable.length;

const rows = codes.map((code) => {
  if (code === SOURCE) return { code, translated: total, total, percent: 100 };
  const catalog = readCatalog(code);
  const translated = translatable.filter((k) => catalog[k] !== undefined && catalog[k] !== source[k]).length;
  return { code, translated, total, percent: total === 0 ? 100 : Math.round((translated / total) * 100) };
});

const ts = `// AUTO-GENERATED by scripts/build-locale-stats.cjs — do not edit.
export interface LocaleCoverage {
  code: string;
  translated: number;
  total: number;
  percent: number;
}
export const LOCALE_COVERAGE: LocaleCoverage[] = ${JSON.stringify(rows)};
`;
fs.writeFileSync(OUT_FILE, ts);
console.log(`locale-coverage: ${rows.length} Sprachen, ${total} zählende Keys → ${OUT_FILE}`);
